package arreglos.ejercicio05;

import java.util.Arrays;

public class InversionVista {

    public void mostrarInversion(int[] original, int[] invertido) {
        System.out.println("=== EJERCICIO 5: INVERSIÓN DE UN ARREGLO ===");
        System.out.println("Arreglo Original : " + Arrays.toString(original));
        System.out.println("Arreglo Invertido: " + Arrays.toString(invertido));
        System.out.println("-----------------------------------------------\n");
    }
}